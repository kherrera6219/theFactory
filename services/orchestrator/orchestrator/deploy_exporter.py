def generate_helm_chart_archive(mission_id: str, mission_data: dict[str, Any]) -> bytes:
    """Generate a gzipped tar archive containing a full Kubernetes Helm Chart."""
    title = (mission_data.get("title") or mission_id).lower().replace(" ", "-")
    sanitized_name = "".join(c for c in title if c.isalnum() or c == "-") or "app"

    chart_yaml = f"""apiVersion: v2
name: {sanitized_name}
description: Helm chart generated by theFactory for mission {mission_id}
type: application
version: 0.1.0
appVersion: "1.0.0"
"""

    values_yaml = f"""# Default values for {sanitized_name}
replicaCount: 1

image:
  repository: local/{sanitized_name}
  pullPolicy: IfNotPresent
  tag: "latest"

service:
  type: ClusterIP
  port: 80

resources:
  limits:
    cpu: 500m
    memory: 512Mi
  requests:
    cpu: 100m
    memory: 128Mi

mission:
  id: "{mission_id}"
  generatedBy: "theFactory"
"""

    deployment_yaml = f"""apiVersion: apps/v1
kind: Deployment
metadata:
  name: {{{{ include "{sanitized_name}.fullname" . }}}}
  labels:
    app.kubernetes.io/name: {sanitized_name}
    thefactory.io/mission-id: "{mission_id}"
spec:
  replicas: {{{{ .Values.replicaCount }}}}
  selector:
    matchLabels:
      app.kubernetes.io/name: {sanitized_name}
  template:
    metadata:
      labels:
        app.kubernetes.io/name: {sanitized_name}
    spec:
      containers:
        - name: {sanitized_name}
          image: "{{{{ .Values.image.repository }}}}:{{{{ .Values.image.tag }}}}"
          imagePullPolicy: {{{{ .Values.image.pullPolicy }}}}
          ports:
            - containerPort: {{{{ .Values.service.port }}}}
          resources:
            {{{{- toYaml .Values.resources | nindent 12 }}}}
"""

    service_yaml = f"""apiVersion: v1
kind: Service
metadata:
  name: {{{{ include "{sanitized_name}.fullname" . }}}}
  labels:
    app.kubernetes.io/name: {sanitized_name}
spec:
  type: {{{{ .Values.service.type }}}}
  ports:
    - port: {{{{ .Values.service.port }}}}
      targetPort: {{{{ .Values.service.port }}}}
      protocol: TCP
      name: http
  selector:
    app.kubernetes.io/name: {sanitized_name}
"""

    helpers_tpl = f"""{{/*
Expand the name of the chart.
*/}}
{{{{- define "{sanitized_name}.fullname" -}}}}
{{{{- .Release.Name | trunc 63 | trimSuffix "-" }}}}
{{{{- end }}}}
"""

    out = io.BytesIO()
    with tarfile.open(fileobj=out, mode="w:gz") as tar:
        files = [
            (f"{sanitized_name}/Chart.yaml", chart_yaml),
            (f"{sanitized_name}/values.yaml", values_yaml),
            (f"{sanitized_name}/templates/_helpers.tpl", helpers_tpl),
            (f"{sanitized_name}/templates/deployment.yaml", deployment_yaml),
            (f"{sanitized_name}/templates/service.yaml", service_yaml),
        ]
        for path_name, content in files:
            data = content.encode("utf-8")
            ti = tarfile.TarInfo(name=path_name)
            ti.size = len(data)
            tar.addfile(ti, io.BytesIO(data))

    return out.getvalue()


def generate_github_actions_workflow(mission_id: str, mission_data: dict[str, Any]) -> str:
    """Generate a GitHub Actions workflow YAML for downstream deployment."""
    title = (mission_data.get("title") or mission_id).lower().replace(" ", "-")
    sanitized_name = "".join(c for c in title if c.isalnum() or c == "-") or "app"

    return f"""# Generated by theFactory for Mission {mission_id}
name: Deploy {sanitized_name}

on:
  push:
    branches: [ main, master ]
  workflow_dispatch:

jobs:
  build-and-deploy:
    runs-on: ubuntu-latest
    steps:
      - name: Checkout Code
        uses: actions/checkout@v4

      - name: Set up Docker Buildx
        uses: docker/setup-buildx-action@v3

      - name: Build Docker Image
        run: |
          docker build -t local/{sanitized_name}:${{{{ github.sha }}}} .

      - name: Verify Audit Evidence Bundle
        run: |
          echo "Verifying mission {mission_id} audit compliance..."

      - name: Deploy Application
        run: |
          echo "Deployment successful for {sanitized_name}"
"""


def _extract_files_map(
    bundle_or_code: str | dict[str, Any] | None,
    *,
    default_filename: str = "main.py",
) -> dict[str, str]:
    """Unpack a multi-file ``## FILE`` bundle or single-file string into a path->content map."""
    if isinstance(bundle_or_code, dict):
        raw_code = str(bundle_or_code.get("code") or bundle_or_code.get("artifact_text") or "")
        fallback_name = str(bundle_or_code.get("filename") or default_filename).strip() or default_filename
    else:
        raw_code = str(bundle_or_code or "")
        fallback_name = default_filename

    if not raw_code.strip():
        return {}
    parsed = parse_file_tree(raw_code)
    if parsed:
        return {entry["path"]: entry["content"] for entry in parsed}
    return {fallback_name: raw_code}


def generate_unified_patch_bundle(
    mission_id: str,
    source_code: str | None,
    generated_output: dict[str, Any] | str | None,
) -> str:
    """Generate a git-apply ready unified diff patch across single- or multi-file bundles."""
    fallback_name = (
        str(generated_output.get("filename") or "main.py")
        if isinstance(generated_output, dict)
        else "main.py"
    )
    before_files = _extract_files_map(source_code, default_filename=fallback_name)
    after_files = _extract_files_map(generated_output, default_filename=fallback_name)

    all_paths = sorted(set(before_files.keys()) | set(after_files.keys()))
    patch_chunks: list[str] = [f"# Unified Patch generated by theFactory for mission {mission_id}\n"]

    for path in all_paths:
        old_text = before_files.get(path, "")
        new_text = after_files.get(path, "")
        if old_text == new_text:
            continue
        old_lines = old_text.splitlines(keepends=True)
        new_lines = new_text.splitlines(keepends=True)
        from_file = f"a/{path}" if path in before_files else "/dev/null"
        to_file = f"b/{path}" if path in after_files else "/dev/null"
        diff_lines = list(
            difflib.unified_diff(
                old_lines,
                new_lines,
                fromfile=from_file,
                tofile=to_file,
            )
        )
        if diff_lines:
            chunk = "".join(diff_lines)
            if not chunk.endswith("\n"):
                chunk += "\n"
            patch_chunks.append(chunk)

    return "".join(patch_chunks)


def generate_cyclonedx_sbom(
    mission_id: str,
    generated_output: dict[str, Any] | None = None,
    dependency_inventory: dict[str, Any] | None = None,
    sbom_delta: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Generate a CycloneDX 1.5 JSON SBOM with cryptographic provenance attestation."""
    output_dict = generated_output if isinstance(generated_output, dict) else {}
    inv_dict = dependency_inventory if isinstance(dependency_inventory, dict) else {}
    delta_dict = sbom_delta if isinstance(sbom_delta, dict) else {}

    language = str(output_dict.get("language") or "python").strip().lower()
    ecosystem = {
        "python": "pypi",
        "javascript": "npm",
        "typescript": "npm",
        "go": "golang",
        "rust": "cargo",
        "java": "maven",
        "csharp": "nuget",
        "ruby": "gem",
    }.get(language, "generic")

    dep_names: list[str] = []
    seen: set[str] = set()

    for candidate in (
        output_dict.get("dependencies"),
        delta_dict.get("remaining"),
        inv_dict.get("dependencies"),
    ):
        if isinstance(candidate, list):
            for item in candidate:
                if isinstance(item, dict):
                    name = str(item.get("name") or "").strip()
                else:
                    name = str(item or "").strip()
                if name and name.lower() not in seen:
                    seen.add(name.lower())
                    dep_names.append(name)

    components: list[dict[str, Any]] = []
    for raw_dep in dep_names:
        if "==" in raw_dep:
            pkg_name, pkg_ver = raw_dep.split("==", 1)
        elif "@" in raw_dep and not raw_dep.startswith("@"):
            pkg_name, pkg_ver = raw_dep.split("@", 1)
        else:
            pkg_name, pkg_ver = raw_dep, "latest"
        pkg_name = pkg_name.strip()
        pkg_ver = pkg_ver.strip() or "latest"
        components.append(
            {
                "type": "library",
                "bom-ref": f"pkg:{ecosystem}/{pkg_name}@{pkg_ver}",
                "name": pkg_name,
                "version": pkg_ver,
                "purl": f"pkg:{ecosystem}/{pkg_name}@{pkg_ver}",
            }
        )

    code_text = str(output_dict.get("code") or "")
    artifact_sha256 = hashlib.sha256(code_text.encode("utf-8")).hexdigest()
    serial_uuid = uuid.uuid5(uuid.NAMESPACE_URL, f"https://thefactory.local/missions/{mission_id}/sbom")

    sbom_core = {
        "bomFormat": "CycloneDX",
        "specVersion": "1.5",
        "serialNumber": f"urn:uuid:{serial_uuid}",
        "version": 1,
        "components": components,
    }
    canonical_payload = json.dumps(sbom_core, sort_keys=True)
    try:
        from shared_runtime.crypto_signing import sign_payload

        signature_record = sign_payload(canonical_payload)
        signature_value = str(signature_record.get("signature") or "")
        signing_algorithm = str(signature_record.get("algorithm") or "HMAC-SHA256")
    except Exception:
        secret = os.getenv("ARTIFACT_SIGNING_SECRET", "thefactory-local-dev-signing-key")
        signature_value = hmac.new(
            secret.encode("utf-8"), canonical_payload.encode("utf-8"), hashlib.sha256
        ).hexdigest()
        signing_algorithm = "HMAC-SHA256"

    return {
        **sbom_core,
        "metadata": {
            "timestamp": datetime.now(UTC).isoformat(),
            "tools": [
                {
                    "vendor": "theFactory",
                    "name": "Holy Grail Refinery SBOM Exporter",
                    "version": "1.1.0",
                }
            ],
            "component": {
                "type": "application",
                "bom-ref": f"mission:{mission_id}",
                "name": str(output_dict.get("filename") or mission_id),
                "hashes": [{"alg": "SHA-256", "content": artifact_sha256}],
            },
            "properties": [
                {"name": "thefactory:mission_id", "value": mission_id},
                {"name": "thefactory:language", "value": language},
                {"name": "thefactory:artifact_sha256", "value": artifact_sha256},
                {"name": "thefactory:signing_algorithm", "value": signing_algorithm},
                {"name": "thefactory:signature", "value": signature_value},
            ],
        },
    }

